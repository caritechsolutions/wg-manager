<?php
declare(strict_types=1);

/** Renders WireGuard configs. Callers must pass a state that passed State::validate(). */
final class Render
{
    public const ROUTE_PROTO = '199'; // marks routes owned by wg-manager

    /**
     * Server config.
     * $forWgQuick = true  → full file for /etc/wireguard/<if>.conf (Address, Table=off, hooks)
     * $forWgQuick = false → stripped form accepted by `wg syncconf`
     */
    public static function server(array $state, string $privateKey, bool $forWgQuick = true, ?int $now = null): string
    {
        $s = $state['settings'];
        $L = [];
        if ($forWgQuick) {
            $L[] = '# Generated by wg-manager ' . WGM_VERSION . ' — do not edit, changes are overwritten.';
            $L[] = '# Manage clients in the web UI or with `wgm`.';
        }
        $L[] = '[Interface]';
        if ($forWgQuick) {
            $L[] = 'Address = ' . $s['address'];
        }
        $L[] = 'ListenPort = ' . (int)$s['listenPort'];
        $L[] = 'PrivateKey = ' . $privateKey;
        if ($forWgQuick) {
            if ($s['mtu'] !== null) {
                $L[] = 'MTU = ' . (int)$s['mtu'];
            }
            $L[] = 'Table = off';
            $L[] = 'PostUp = ' . WGM_HELPER_PATH_FOR_HOOKS . ' hook-up %i';
            $L[] = 'PostDown = ' . WGM_HELPER_PATH_FOR_HOOKS . ' hook-down %i';
        }
        foreach (self::activeClients($state, $now) as $c) {
            $L[] = '';
            if ($forWgQuick) {
                $L[] = '# ' . preg_replace('/[\x00-\x1F\x7F]/', '', $c['name']) . ' (' . $c['id'] . ')';
            }
            $L[] = '[Peer]';
            $L[] = 'PublicKey = ' . $c['publicKey'];
            if (!empty($c['presharedKey'])) {
                $L[] = 'PresharedKey = ' . $c['presharedKey'];
            }
            $L[] = 'AllowedIPs = ' . implode(', ', array_merge([$c['address'] . '/32'], $c['serverRoutes']));
        }
        return implode("\n", $L) . "\n";
    }

    /** @return array<string,array> */
    public static function activeClients(array $state, ?int $now = null): array
    {
        $out = array_filter($state['clients'], fn($c) => State::isActive($c, $now));
        uasort($out, fn($a, $b) => ip2long($a['address']) <=> ip2long($b['address']));
        return $out;
    }

    /** Routes the hub must point into the tunnel: CIDR => client name. @return array<string,string> */
    public static function routes(array $state, ?int $now = null): array
    {
        $r = [];
        foreach (self::activeClients($state, $now) as $c) {
            foreach ($c['serverRoutes'] as $cidr) {
                $r[$cidr] = $c['name'];
            }
        }
        ksort($r);
        return $r;
    }

    /** Client config file. */
    public static function client(array $state, array $c): string
    {
        $s = $state['settings'];
        $host = $s['endpointHost'] !== '' ? $s['endpointHost'] : '[SERVER_ADDRESS]';
        if (strpos($host, ':') !== false) {
            $host = '[' . $host . ']';
        }
        $L = [];
        $L[] = '# ' . $c['name'] . ' — generated by wg-manager';
        $L[] = '[Interface]';
        $L[] = 'PrivateKey = ' . ($c['privateKey'] ?? '<PASTE_THIS_DEVICE_PRIVATE_KEY>');
        $L[] = 'Address = ' . $c['address'] . '/32';
        if (trim((string)$c['dns']) !== '') {
            $L[] = 'DNS = ' . implode(', ', Ip::splitList($c['dns']));
        }
        if ($c['mtu'] !== null) {
            $L[] = 'MTU = ' . (int)$c['mtu'];
        }
        $L[] = '';
        $L[] = '[Peer]';
        $L[] = 'PublicKey = ' . $state['server']['publicKey'];
        if (!empty($c['presharedKey'])) {
            $L[] = 'PresharedKey = ' . $c['presharedKey'];
        }
        $L[] = 'AllowedIPs = ' . implode(', ', State::clientAllowedIps($state, $c));
        if ((int)$c['keepalive'] > 0) {
            $L[] = 'PersistentKeepalive = ' . (int)$c['keepalive'];
        }
        $L[] = 'Endpoint = ' . $host . ':' . (int)$s['endpointPort'];
        return implode("\n", $L) . "\n";
    }

    /**
     * Install script for a new device: installs WireGuard, writes this
     * client's config and brings the tunnel up. Served by a setup link and
     * meant for `curl … | sudo bash`.
     */
    public static function setupScript(array $state, array $c): string
    {
        $conf = self::client($state, $c);
        $label = self::clientFilename($c);
        $hub = Ip::ifaceV4($state['settings']['address'])['server'] ?? '';
        $needsResolvconf = trim((string)$c['dns']) !== '';
        $L = [];
        $L[] = '#!/bin/bash';
        $L[] = '# WireGuard client setup for ' . $label . ' — generated by wg-manager';
        $L[] = 'set -euo pipefail';
        $L[] = '';
        $L[] = 'main() {';
        $L[] = '  WG_IF="${WG_IF:-wg0}"';
        $L[] = "  HUB_IP='" . $hub . "'";
        $L[] = '  CONF="/etc/wireguard/${WG_IF}.conf"';
        $L[] = '';
        $L[] = '  if [ "$(id -u)" != "0" ]; then';
        $L[] = '    echo "This must be run as root (add sudo before bash)." >&2; exit 1';
        $L[] = '  fi';
        $L[] = '  case "$WG_IF" in';
        $L[] = '    ""|*[!A-Za-z0-9_-]*) echo "Invalid interface name: $WG_IF" >&2; exit 1 ;;';
        $L[] = '  esac';
        $L[] = '';
        $L[] = "  echo '==> WireGuard setup for " . $label . "'";
        $L[] = '';
        $L[] = '  if ! command -v wg-quick >/dev/null 2>&1; then';
        $L[] = '    if command -v apt-get >/dev/null 2>&1; then';
        $L[] = '      echo "==> Installing WireGuard..."';
        $L[] = '      export DEBIAN_FRONTEND=noninteractive';
        $L[] = '      apt-get update -qq || true';
        $L[] = '      apt-get install -y -qq wireguard-tools';
        $L[] = '    else';
        $L[] = '      echo "WireGuard (wg-quick) is not installed and this system has no apt-get. Install WireGuard, then run this again." >&2; exit 1';
        $L[] = '    fi';
        $L[] = '  fi';
        if ($needsResolvconf) {
            $L[] = '  if ! command -v resolvconf >/dev/null 2>&1 && command -v apt-get >/dev/null 2>&1; then';
            $L[] = '    echo "==> Installing resolvconf (this config sets DNS)..."';
            $L[] = '    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq resolvconf || echo "WARNING: could not install resolvconf; the tunnel may fail to start because the config sets DNS." >&2';
            $L[] = '  fi';
        }
        $L[] = '';
        $L[] = '  mkdir -p /etc/wireguard';
        $L[] = '  chmod 700 /etc/wireguard';
        $L[] = '  if [ -f "$CONF" ]; then';
        $L[] = '    BAK="$CONF.bak-$(date +%Y%m%d-%H%M%S)"';
        $L[] = '    cp -p "$CONF" "$BAK"';
        $L[] = '    echo "==> Existing config saved as $BAK"';
        $L[] = '  fi';
        $L[] = '  umask 077';
        $L[] = "  cat > \"\$CONF\" <<'WGM_CONF_EOF'";
        $L[] = rtrim($conf, "\n");
        $L[] = 'WGM_CONF_EOF';
        $L[] = '  chmod 600 "$CONF"';
        $L[] = '  echo "==> Config written to $CONF"';
        $L[] = '';
        $L[] = '  echo "==> Starting the tunnel..."';
        $L[] = '  if command -v systemctl >/dev/null 2>&1; then';
        $L[] = '    systemctl enable "wg-quick@${WG_IF}" >/dev/null 2>&1 || true';
        $L[] = '    if ! systemctl restart "wg-quick@${WG_IF}"; then';
        $L[] = '      echo "ERROR: the tunnel did not start. Details: systemctl status wg-quick@${WG_IF}" >&2; exit 1';
        $L[] = '    fi';
        $L[] = '  else';
        $L[] = '    wg-quick down "$WG_IF" >/dev/null 2>&1 || true';
        $L[] = '    wg-quick up "$WG_IF"';
        $L[] = '  fi';
        $L[] = '';
        if ($hub !== '') {
            $L[] = '  sleep 3';
            $L[] = '  if ping -c 3 -W 2 "$HUB_IP" >/dev/null 2>&1; then';
            $L[] = "    echo '==> Done. The tunnel is up (this device is " . $c['address'] . ").'";
            $L[] = '  else';
            $L[] = '    echo "WARNING: WireGuard is installed and started, but the hub ($HUB_IP) did not answer. Check that this network allows outbound UDP." >&2';
            $L[] = '    exit 2';
            $L[] = '  fi';
        } else {
            $L[] = "  echo '==> Done. WireGuard is installed and started.'";
        }
        $L[] = '}';
        $L[] = '';
        $L[] = 'main "$@"';
        return implode("\n", $L) . "\n";
    }

    /** Script served for a bad or expired setup link (so `| bash` prints a clear message). */
    public static function setupError(string $msg): string
    {
        return "#!/bin/bash\necho '" . str_replace("'", '', $msg) . "' >&2\nexit 1\n";
    }

    public static function clientFilename(array $c): string
    {
        $n = preg_replace('/[^A-Za-z0-9_-]+/', '-', $c['name']);
        return trim(substr((string)$n, 0, 15), '-') ?: 'wg-client';
    }
}

if (!defined('WGM_HELPER_PATH_FOR_HOOKS')) {
    define('WGM_HELPER_PATH_FOR_HOOKS', '/usr/local/sbin/wg-manager-helper');
}

#!/usr/bin/env bash
#
# wg-manager uninstaller.
#
#   sudo ./uninstall.sh            stop the hub and remove the app; keep data (state, users, keys, backups)
#   sudo ./uninstall.sh --purge    also delete all data, including the server private key
#
set -euo pipefail
[[ $EUID -eq 0 ]] || { echo "run as root" >&2; exit 1; }

PURGE=0
[[ "${1:-}" == "--purge" ]] && PURGE=1

STATE_DIR=/var/lib/wg-manager
KEY_DIR=/etc/wireguard/wg-manager

IFACE=""
if [[ -f "$KEY_DIR/active-interface" ]]; then IFACE="$(tr -d '\n' <"$KEY_DIR/active-interface")"; fi

if [[ $PURGE -eq 1 ]]; then
  read -r -p "This deletes all clients, backups and the server key. Type DELETE to continue: " ok
  [[ "$ok" == "DELETE" ]] || { echo "aborted"; exit 1; }
fi

systemctl disable --now wg-manager-tick.timer 2>/dev/null || true
rm -f /etc/systemd/system/wg-manager-tick.timer /etc/systemd/system/wg-manager-tick.service

if [[ -n "$IFACE" && "$IFACE" =~ ^[a-zA-Z0-9_=+.-]{1,15}$ ]]; then
  echo "Stopping wg-quick@$IFACE"
  systemctl disable --now "wg-quick@$IFACE" 2>/dev/null || true
  if [[ -f "/etc/wireguard/$IFACE.conf" ]] && head -1 "/etc/wireguard/$IFACE.conf" | grep -q '^# Generated by wg-manager'; then
    if [[ $PURGE -eq 1 ]]; then rm -f "/etc/wireguard/$IFACE.conf"; else mv "/etc/wireguard/$IFACE.conf" "/etc/wireguard/$IFACE.conf.wg-manager-bak"; fi
  fi
fi

rm -f /etc/nginx/sites-enabled/wg-manager /etc/nginx/sites-available/wg-manager \
      /etc/nginx/sites-enabled/wg-manager-acme /etc/nginx/sites-available/wg-manager-acme
systemctl reload nginx 2>/dev/null || true
rm -f /etc/sudoers.d/wg-manager /usr/local/sbin/wg-manager-helper /usr/local/bin/wgm /etc/sysctl.d/99-wg-manager.conf
rm -rf /opt/wg-manager
systemctl daemon-reload

if [[ $PURGE -eq 1 ]]; then
  rm -rf "$STATE_DIR" "$KEY_DIR" /etc/wg-manager /var/www/wg-manager-acme
  echo "wg-manager removed, data deleted."
else
  echo "wg-manager removed. Data kept in $STATE_DIR and $KEY_DIR — reinstalling picks it up again."
fi
